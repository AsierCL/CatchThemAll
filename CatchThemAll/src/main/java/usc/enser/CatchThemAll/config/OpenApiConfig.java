package usc.enser.CatchThemAll.config;

import java.util.List;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.servers.Server;

/**
 * OpenAPI document metadata for the CatchThemAll REST API.
 *
 * <p>The document itself is generated by springdoc from the controllers and DTOs, so this bean only
 * carries the information that cannot be derived from code: title, description, servers and the
 * bearer security scheme declared but not globally required (each operation opts in).</p>
 */
@Configuration
public class OpenApiConfig {

    public static final String BEARER_SCHEME = "bearerAuth";

    @Bean
    OpenAPI catchThemAllOpenApi() {
        return new OpenAPI()
                .info(new Info()
                        .title("CatchThemAll API")
                        .version("0.0.1-SNAPSHOT")
                        .summary("Pokedex de famosos con capturas por reconocimiento facial")
                        .description("""
                                API REST de CatchThemAll. Permite registrarse, autenticarse con JWT, consultar el
                                catalogo de famosos, gestionar amistades y registrar capturas de un famoso a partir
                                de una fotografia validada por el servicio de reconocimiento facial.

                                ## Autenticacion
                                `POST /auth/register` y `POST /auth/login` devuelven un token JWT (`HS256`, vigencia de
                                15 minutos). Enviarlo como `Authorization: Bearer <token>` en las operaciones que lo
                                requieren.

                                ## Errores
                                Todos los errores comparten el esquema `ErrorDTO`: `timestamp`, `status`, `error`,
                                `message`, `path` y una lista `details` con el detalle por campo cuando la causa es una
                                validacion.

                                ## Notas de la version actual
                                En esta version de desarrollo el filtro de seguridad deja pasar todas las peticiones
                                (`.anyRequest().permitAll()`). El token solo se exige en las operaciones que resuelven
                                al usuario autenticado, como `GET /users/me` y el historial de capturas propias.
                                """)
                        .contact(new Contact()
                                .name("Equipo CatchThemAll")
                                .url("https://github.com/AsierCL/CatchThemAll"))
                        .license(new License().name("Uso academico")))
                .servers(List.of(new Server()
                        .url("http://localhost:8080")
                        .description("Entorno local de desarrollo")))
                .components(new Components()
                        .addSecuritySchemes(BEARER_SCHEME, new SecurityScheme()
                                .type(SecurityScheme.Type.HTTP)
                                .scheme("bearer")
                                .bearerFormat("JWT")
                                .description("""
                                        Token JWT obtenido en `POST /auth/login` o `POST /auth/register`.
                                        Formato: `Authorization: Bearer <token>`.
                                        """)));
    }
}
