package usc.enser.CatchThemAll.config;

import java.time.Duration;
import java.util.List;

import org.springframework.beans.factory.ObjectProvider;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.info.BuildProperties;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.servers.Server;

/**
 * OpenAPI document metadata for the CatchThemAll REST API.
 *
 * <p>The document itself is generated by springdoc from the controllers and DTOs, so this bean only
 * carries the information that cannot be derived from code: title, description, servers and the
 * bearer security scheme declared but not globally required (each operation opts in).</p>
 *
 * <p>The cache windows printed in the description come from the same properties {@link CacheConfig}
 * uses, so the text cannot drift from the cache that is actually running.</p>
 */
@Configuration
public class OpenApiConfig {

    public static final String BEARER_SCHEME = "bearerAuth";

    private final Duration famousTtl;
    private final Duration rankingTtl;
    private final Duration capturesTtl;

    public OpenApiConfig(@Value("${cache.famous.ttl:PT24H}") Duration famousTtl,
                         @Value("${cache.ranking.ttl:PT1H}") Duration rankingTtl,
                         @Value("${cache.captures.ttl:PT15M}") Duration capturesTtl) {
        this.famousTtl = famousTtl;
        this.rankingTtl = rankingTtl;
        this.capturesTtl = capturesTtl;
    }

    @Bean
    OpenAPI catchThemAllOpenApi(ObjectProvider<BuildProperties> buildProperties) {
        return new OpenAPI()
                .info(new Info()
                        .title("CatchThemAll API")
                        .version(apiVersion(buildProperties))
                        .summary("Pokedex de famosos con capturas por reconocimiento facial")
                        .description(description())
                        .contact(new Contact()
                                .name("Equipo CatchThemAll")
                                .url("https://github.com/AsierCL/CatchThemAll"))
                        .license(new License().name("Uso academico")))
                .servers(List.of(new Server()
                        .url("http://localhost:8080")
                        .description("Entorno local de desarrollo")))
                .components(new Components()
                        .addSecuritySchemes(BEARER_SCHEME, new SecurityScheme()
                                .type(SecurityScheme.Type.HTTP)
                                .scheme("bearer")
                                .bearerFormat("JWT")
                                .description("""
                                        Token JWT obtenido en `POST /auth/login` o `POST /auth/register`.
                                        Formato: `Authorization: Bearer <token>`.
                                        """)));
    }

    private String description() {
        return """
                API REST de CatchThemAll. Permite registrarse, autenticarse con JWT, consultar el
                catalogo de famosos, gestionar amistades y registrar capturas de un famoso a partir
                de una fotografia validada por el servicio de reconocimiento facial.

                ## Autenticacion
                `POST /auth/register` y `POST /auth/login` devuelven un par de tokens: un JWT
                (`HS256`, vigencia de 15 minutos) y un `refreshToken` opaco de 24 horas. El JWT se
                envia como `Authorization: Bearer <token>` y se renueva con `POST /auth/refresh`.

                ## Cache y validacion
                Varias lecturas se sirven desde una cache en memoria: `GET /famous` hasta %s,
                `GET /users/ranking` hasta %s y `GET /captures/me` hasta %s. Durante esa ventana la
                respuesta puede no reflejar la ultima escritura.

                Las respuestas con cuerpo llevan `ETag`. Si se repite la peticion con `If-None-Match`,
                el servidor puede contestar `304 Not Modified` sin cuerpo. Las cabeceras incluyen
                `Cache-Control: no-store`, asi que ningun intermediario guarda la respuesta: la
                revalidacion por `ETag` solo ahorra el cuerpo, no la ida y vuelta.

                ## Errores
                Todos los errores comparten el esquema `ErrorDTO`: `timestamp`, `status`, `error`,
                `message`, `path` y una lista `details` con el detalle por campo cuando la causa es una
                validacion.

                ## Notas de la version actual
                En esta version de desarrollo el filtro de seguridad deja pasar todas las peticiones
                (`.anyRequest().permitAll()`). El token solo se exige en las operaciones que resuelven
                al usuario autenticado, como `GET /users/me` y el historial de capturas propias.
                """.formatted(human(famousTtl), human(rankingTtl), human(capturesTtl));
    }

    /**
     * Presenta una duracion con la unidad mas grande que la represente de forma exacta.
     */
    private String human(Duration duration) {
        long days = duration.toDays();
        if (days > 0 && duration.equals(Duration.ofDays(days))) {
            return days == 1 ? "1 dia" : days + " dias";
        }
        long hours = duration.toHours();
        if (hours > 0 && duration.equals(Duration.ofHours(hours))) {
            return hours == 1 ? "1 hora" : hours + " horas";
        }
        long minutes = duration.toMinutes();
        if (minutes > 0 && duration.equals(Duration.ofMinutes(minutes))) {
            return minutes == 1 ? "1 minuto" : minutes + " minutos";
        }
        return duration.toSeconds() + " segundos";
    }

    /**
     * La version sale de {@code META-INF/build-info.properties}, que genera el plugin de Maven, para no
     * duplicar el numero que vive en el pom. Si el recurso no existe (por ejemplo al correr desde el IDE
     * sin empaquetar) se informa {@code dev}.
     */
    private String apiVersion(ObjectProvider<BuildProperties> buildProperties) {
        BuildProperties properties = buildProperties.getIfAvailable();
        if (properties == null || properties.getVersion() == null || properties.getVersion().isBlank()) {
            return "dev";
        }
        return properties.getVersion();
    }
}
